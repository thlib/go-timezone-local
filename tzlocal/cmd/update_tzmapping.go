package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
	_ "time/tzdata"

	"github.com/thlib/go-timezone-local/tzdata"
)

func main() {
	if err := update("tzlocal/tzmapping.go", tzdata.UpdateWindowsTZMapping); err != nil {
		fmt.Fprintln(os.Stderr, "Mapping update blocked:", err)
		os.Exit(1)
	}
}

func update(path string, generate func(io.Writer) error) error {
	previous, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by tzlocal/cmd/update_tzmapping.go DO NOT EDIT.\n")
	out.WriteString("//go:build windows\n// +build windows\n\n")
	out.WriteString("package tzlocal\n\n")
	if err := generate(&out); err != nil {
		return err
	}

	generated, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	old, err := readTables(previous)
	if err != nil {
		return fmt.Errorf("existing mapping: %w", err)
	}
	next, err := readTables(generated)
	if err != nil {
		return fmt.Errorf("candidate mapping: %w", err)
	}
	if err := validateTables(next); err != nil {
		return err
	}
	changed := false
	var failures []string
	for _, name := range []string{"WinTZtoIANA", "IANAtoWinTZ"} {
		different, err := compareTable(name, old[name], next[name])
		changed = changed || different
		if err != nil {
			failures = append(failures, err.Error())
		}
	}
	if len(failures) != 0 {
		return fmt.Errorf("%s", strings.Join(failures, "; "))
	}
	if !changed {
		fmt.Println("Mappings unchanged; leaving existing file untouched.")
		return nil
	}
	// Replace only after every check passes. A failed write leaves the old file intact.
	f, err := os.CreateTemp(filepath.Dir(path), ".tzmapping-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(generated); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(f.Name(), path); err != nil {
		return err
	}
	fmt.Printf("Successfully updated %s\n", path)
	return nil
}

type tables map[string]map[string]string

// Parse Go literals so comments, dates and formatting cannot trigger an update.
func readTables(source []byte) (tables, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "tzmapping.go", source, 0)
	if err != nil {
		return nil, err
	}
	result := tables{}
	for _, decl := range f.Decls {
		d, ok := decl.(*ast.GenDecl)
		if !ok || d.Tok != token.VAR {
			continue
		}
		for _, spec := range d.Specs {
			s, ok := spec.(*ast.ValueSpec)
			if !ok || len(s.Names) != 1 || len(s.Values) != 1 {
				return nil, fmt.Errorf("unexpected declaration")
			}
			name := s.Names[0].Name
			if name != "WinTZtoIANA" && name != "IANAtoWinTZ" {
				return nil, fmt.Errorf("unexpected table %s", name)
			}
			if _, exists := result[name]; exists {
				return nil, fmt.Errorf("duplicate table %s", name)
			}
			literal, ok := s.Values[0].(*ast.CompositeLit)
			if !ok {
				return nil, fmt.Errorf("%s is not a map literal", name)
			}
			mapType, ok := literal.Type.(*ast.MapType)
			if !ok {
				return nil, fmt.Errorf("%s must be map[string]string", name)
			}
			keyType, keyOK := mapType.Key.(*ast.Ident)
			valueType, valueOK := mapType.Value.(*ast.Ident)
			if !keyOK || !valueOK || keyType.Name != "string" || valueType.Name != "string" {
				return nil, fmt.Errorf("%s must be map[string]string", name)
			}
			m := map[string]string{}
			for _, entry := range literal.Elts {
				pair, ok := entry.(*ast.KeyValueExpr)
				if !ok {
					return nil, fmt.Errorf("invalid entry in %s", name)
				}
				key, err := stringLiteral(pair.Key)
				if err != nil {
					return nil, err
				}
				value, err := stringLiteral(pair.Value)
				if err != nil {
					return nil, err
				}
				if _, exists := m[key]; exists {
					return nil, fmt.Errorf("duplicate key %q in %s", key, name)
				}
				m[key] = value
			}
			result[name] = m
		}
	}
	if len(result["WinTZtoIANA"]) == 0 || len(result["IANAtoWinTZ"]) == 0 {
		return nil, fmt.Errorf("both mapping tables must be nonempty")
	}
	return result, nil
}

func stringLiteral(expr ast.Expr) (string, error) {
	literal, ok := expr.(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return "", fmt.Errorf("expected string literal")
	}
	s, err := strconv.Unquote(literal.Value)
	if err != nil {
		return "", err
	}
	if strings.TrimSpace(s) == "" {
		return "", fmt.Errorf("empty mapping key or value")
	}
	return s, nil
}

func validateTables(m tables) error {
	for windows, iana := range m["WinTZtoIANA"] {
		if _, ok := m["IANAtoWinTZ"][iana]; !ok {
			return fmt.Errorf("%q has no reverse IANA entry %q", windows, iana)
		}
	}
	for iana, windows := range m["IANAtoWinTZ"] {
		if _, ok := m["WinTZtoIANA"][windows]; !ok {
			return fmt.Errorf("%q references missing Windows zone %q", iana, windows)
		}
		if _, err := time.LoadLocation(iana); err != nil {
			return fmt.Errorf("invalid IANA zone %q: %w", iana, err)
		}
	}
	return nil
}

func compareTable(name string, old, next map[string]string) (bool, error) {
	unchanged := 0
	var removed, changed []string
	for key, value := range old {
		newValue, exists := next[key]
		switch {
		case !exists:
			removed = append(removed, key)
		case value != newValue:
			changed = append(changed, fmt.Sprintf("%s: %s -> %s", key, value, newValue))
		default:
			unchanged++
		}
	}
	sort.Strings(removed)
	sort.Strings(changed)
	size := len(old)
	if len(next) > size {
		size = len(next)
	}
	if size == 0 {
		return false, fmt.Errorf("%s is empty", name)
	}
	fmt.Printf("%s: %d -> %d entries, %.2f%% identical; removed=%q; changed=%q\n", name, len(old), len(next), 100*float64(unchanged)/float64(size), removed, changed)
	if len(removed) > 0 {
		return true, fmt.Errorf("%s lost keys: %q", name, removed)
	}
	if unchanged*100 < size*90 {
		return true, fmt.Errorf("%s is less than 90%% identical", name)
	}
	return unchanged != len(old) || unchanged != len(next), nil
}
